# ELK Stack: Conjunto de ferramentas composto por Elasticsearch, Logstash e Kibana, utilizado para centralizar, analisar e visualizar logs de aplicações de forma eficiente.

# Filebeat: Ferramenta leve que envia logs de arquivos para o Logstash ou Elasticsearch, facilitando a coleta e centralização de dados de log.

# Kibana Query Language (KQL): Linguagem de consulta utilizada no Kibana para filtrar e buscar dados em logs, permitindo a criação de visualizações personalizadas e relatórios.

# Observabilidade: Capacidade de medir o estado interno de um sistema com base nos logs, métricas e rastreamentos, essencial para monitorar e melhorar o desempenho de aplicações.

# Sintaxe JSON: Formato de dados leve e de fácil leitura para humanos e máquinas, usado para estruturar e transmitir informações de logs no ELK Stack.

# Visualização de Logs: Processo de transformar dados brutos de logs em gráficos e relatórios compreensíveis, facilitando a análise e comunicação de informações técnicas.




# O que é o ELK Stack e para que ele é utilizado?: O ELK Stack é uma combinação de três ferramentas de código aberto: Elasticsearch, Logstash e Kibana. Ele é utilizado para centralizar, analisar e visualizar logs de aplicações, permitindo um gerenciamento eficiente de logs e monitoramento de sistemas.


# Como os logs de uma aplicação FastAPI são enviados para o ELK Stack?: Os logs de uma aplicação FastAPI são enviados para o ELK Stack utilizando ferramentas como Filebeat e Logstash, que coletam e enviam dados para o Elasticsearch. Isso permite centralizar o gerenciamento de logs, especialmente em ambientes que utilizam containers Docker e arquiteturas baseadas em Kubernetes.


# Qual é a função do Kibana no ELK Stack?: O Kibana é uma ferramenta de visualização que se conecta ao Elasticsearch, permitindo a análise e visualização dos logs em tempo real. Ele facilita a criação de dashboards interativos, a análise de dados e a identificação de padrões ou problemas.


# Como o ELK Stack ajuda no monitoramento de desempenho de aplicações?: O ELK Stack ajuda no monitoramento de desempenho de aplicações ao centralizar e analisar logs, permitindo identificar gargalos e problemas de performance que possam afetar a experiência do usuário ou a eficiência do sistema.


# O que é KQL e como é utilizado no Kibana?: KQL (Kibana Query Language) é uma linguagem de consulta utilizada no Kibana para filtrar dados em JSON. Ela permite a aplicação de filtros de logs em sistemas de monitoramento, facilitando a análise de dados específicos.


# Quais são as vantagens de criar dashboards no Elasticsearch?: Criar dashboards no Elasticsearch permite transformar dados brutos em visualizações compreensíveis, facilitando a comunicação de informações técnicas para áreas de negócios e auxiliando na tomada de decisões estratégicas.


# Como o Docker Compose é utilizado no contexto do ELK Stack?: O Docker Compose é utilizado para integrar o Kibana, Logstash e Elasticsearch, permitindo levantar o ambiente do ELK Stack de forma simplificada e simular o ambiente de produção para testes e desenvolvimento.


# Quais são as diferenças entre o ELK Stack e outras ferramentas de monitoramento como New Relic e Datadog?: O ELK Stack, New Relic e Datadog são ferramentas de monitoramento com funcionalidades semelhantes, mas diferem em suas operações. O ELK Stack é uma solução de código aberto que oferece flexibilidade e personalização, enquanto New Relic e Datadog são soluções comerciais que oferecem integração e suporte mais abrangentes.


# Por que é importante configurar alertas no Kibana?: Configurar alertas no Kibana é importante para receber notificações sobre eventos críticos, como erros ou falhas no sistema, permitindo uma resposta rápida a problemas que possam afetar o desempenho ou a segurança da aplicação.


# Como a prática de integrar uma aplicação FastAPI com o ELK Stack ajuda no aprendizado?: A prática de integrar uma aplicação FastAPI com o ELK Stack consolida o aprendizado ao permitir que os alunos apliquem os conceitos teóricos em um cenário prático, preparando-os para o projeto final do curso e para situações reais no ambiente de trabalho.
